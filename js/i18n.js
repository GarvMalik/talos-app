// Current 2-letter code, derived from the saved TTS language ('fi-FI' -> 'fi')
function _talosLangCode() {
    return (localStorage.getItem('ttsLanguage') || 'en-US').split('-')[0];
}

// Translate a key with English fallback
function t(key) {
    const dict = TALOS_I18N[_talosLangCode()] || TALOS_I18N.en;
    return dict[key] || TALOS_I18N.en[key] || key;
}

// Swap every tagged element. data-i18n -> textContent,
// data-i18n-ph -> placeholder. Quick-reply buttons also get their
// sent value translated so the transcript matches what the user tapped.
function applyTranslations(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n);
        if (el.hasAttribute('data-quick-reply')) el.dataset.quickReply = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach(el => {
        el.placeholder = t(el.dataset.i18nPh);
        // Placeholder-only inputs have no accessible name — mirror it.
        el.setAttribute('aria-label', t(el.dataset.i18nPh));
    });
    const code = _talosLangCode();
    document.documentElement.lang = code;
    document.documentElement.dir = (code === 'ar') ? 'rtl' : 'ltr';
}
